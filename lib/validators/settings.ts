import { z } from "zod";

export const settingsSchema = z.object({
  church_name: z.string().trim().min(3),
  subtitle: z.string().trim().min(3),
  branch_name: z.string().trim().min(3),
  address: z.string().trim().min(8),
  phone_primary: z.string().trim().min(7),
  phone_secondary: z.string().trim().min(7),
  tagline: z.string().trim().min(3),
  minister_in_charge: z.string().trim().min(3),
  about: z.string().trim().min(10),
  logo_url: z.string().trim().min(1),
  campaign_title: z.string().trim().min(3),
  campaign_theme: z.string().trim().min(3),
  campaign_scripture: z.string().trim().min(3),
  campaign_time: z.string().trim().min(3),
  campaign_venue: z.string().trim().min(3),
  campaign_start_date: z.string().min(8),
  campaign_end_date: z.string().min(8),
  maps_embed_url: z.string().trim().default(""),
  maps_link: z.string().trim().default(""),
  facebook: z.string().trim().optional(),
  instagram: z.string().trim().optional(),
  youtube: z.string().trim().optional(),
  bank_name: z.string().trim().optional(),
  bank_account_name: z.string().trim().optional(),
  bank_account_number: z.string().trim().optional(),
});
